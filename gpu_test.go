func TestDraw(t *testing.T) {
	c8 := Chip8{}
	c8.reset()
	c8.pgCtr = 0x0
	c8.addrI = 0x0001

	oc := uint16(0xD23A)
	sprite := [11]byte{
		0b00000000,
		0b01111100,
		0b01100100,
		0b01010100,
		0b01001100,
		0b01001100,
		0b01001100,
		0b01010100,
		0b01100100,
		0b01111100,
		0b00000000,
	}
	c := c8.addrI
	for _, b := range sprite {
		c8.mem[c] = b
		c++
	}

	c8.cycle(oc)

	if c8.reg[0xF] == 0x0001 {
		t.Logf("expected c8.reg[0xF] to be 0, was %+v", c8.reg[0xF])
		t.Fail()
	}

	oc = uint16(0xD235)
	c8.reg[0x2] = 0x0005
	c8.reg[0x3] = 0x0009
	sprite = [11]byte{
		0b10001000,
		0b01010000,
		0b00100000,
		0b01010000,
		0b10001000,
	}
	c = c8.addrI
	for _, b := range sprite {
		c8.mem[c] = b
		c++
	}

	c8.cycle(oc)

	if c8.reg[0xF] != 0x0001 {
		t.Logf("expected c8.reg[0xF] to be 1, was %+v", c8.reg[0xF])
		t.Fail()
	}

	oc = uint16(0xD231)
	c8.reg[0x2] = byte(int(0))
	c8.reg[0x3] = byte(int(0))
	sprite = [11]byte{
		0b11111111,
	}
	c = c8.addrI
	for _, b := range sprite {
		c8.mem[c] = b
		c++
	}

	c8.cycle(oc)

	oc = uint16(0xD231)
	c8.reg[0x2] = byte(int(64 - 4))
	c8.reg[0x3] = byte(int(31))
	sprite = [11]byte{
		0b11111111,
	}
	c = c8.addrI
	for _, b := range sprite {
		c8.mem[c] = b
		c++
	}

	c8.cycle(oc)

	oc = uint16(0xD235)
	c8.reg[0x2] = byte(int(31))
	c8.reg[0x3] = byte(int(33))
	sprite = [11]byte{
		0b10000000,
		0b10000000,
		0b10000000,
		0b10000000,
		0b10000000,
	}
	c = c8.addrI
	for _, b := range sprite {
		c8.mem[c] = b
		c++
	}

	c8.cycle(oc)

	for y := 0; y < len(c8.GetBuffer()); y++ {
		for x := 0; x < len(c8.GetBuffer()[0]); x++ {
			if c8.GetBuffer()[y][x] != expectedBuffer[y][x] {
				t.Logf("buffer at X(%d) Y(%d) expected to be %+v, was %v", x, y, expectedBuffer[y][x], c8.buffer[y][x])
				t.Fail()
			}
		}
	}
}

func TestClear(t *testing.T) {
	c8 := Chip8{}

	for y := 0; y < len(c8.GetBuffer()); y++ {
		for x := 0; x < len(c8.GetBuffer()[0]); x++ {
			c8.buffer[y][x] = 0x1
		}
	}

	c8.displayClear()

	for y := 0; y < len(c8.GetBuffer()); y++ {
		for x := 0; x < len(c8.GetBuffer()[0]); x++ {
			if c8.GetBuffer()[y][x] != 0x0 {
				t.Logf("buffer at X(%d) Y(%d) expected to be 0, was %v", x, y, c8.GetBuffer()[y][x])
				t.Fail()
			}
		}
	}
}
